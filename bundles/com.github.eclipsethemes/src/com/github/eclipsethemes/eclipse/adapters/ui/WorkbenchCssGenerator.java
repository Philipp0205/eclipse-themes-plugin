package com.github.eclipsethemes.eclipse.adapters.ui;

import com.github.eclipsethemes.core.models.Theme;
import com.github.eclipsethemes.core.models.TokenKey;

/**
 * Generates the small overlay applied after Eclipse's platform-specific base
 * theme. Keeping this separate from the base theme lets Eclipse retain its
 * GTK, Cocoa and Win32 renderer rules.
 */
public final class WorkbenchCssGenerator {

	private WorkbenchCssGenerator() {
	}

	public static String generate(Theme theme) {
		String background = theme.get(TokenKey.BACKGROUND).getColor().toString();
		String foreground = theme.get(TokenKey.FOREGROUND).getColor().toString();
		String selectionBackground = theme.get(TokenKey.SELECTION_BACKGROUND).getColor().toString();
		String selectionForeground = theme.get(TokenKey.SELECTION_FOREGROUND).getColor().toString();
		String currentLine = theme.get(TokenKey.CURRENT_LINE).getColor().toString();

		return """
				/* Generated by Eclipse Themes. Changes are overwritten. */
				ColorDefinition#org-eclipse-ui-workbench-DARK_BACKGROUND { color: %s; }
				ColorDefinition#org-eclipse-ui-workbench-DARK_FOREGROUND { color: %s; }
				ColorDefinition#org-eclipse-ui-workbench-ACTIVE_TAB_BG_START { color: %s; }
				ColorDefinition#org-eclipse-ui-workbench-ACTIVE_TAB_BG_END { color: %s; }
				ColorDefinition#org-eclipse-ui-workbench-ACTIVE_TAB_TEXT_COLOR { color: %s; }
				ColorDefinition#org-eclipse-ui-workbench-INACTIVE_TAB_BG_START { color: %s; }
				ColorDefinition#org-eclipse-ui-workbench-INACTIVE_TAB_BG_END { color: %s; }
				ColorDefinition#org-eclipse-ui-workbench-INACTIVE_TAB_TEXT_COLOR { color: %s; }

				Shell, Composite, Group, Sash, SashForm, ScrolledComposite, ExpandBar {
				    background-color: %s;
				    color: %s;
				}
				Tree, Table, List {
				    background-color: %s;
				    color: %s;
				    swt-selection-background-color: %s;
				    swt-selection-foreground-color: %s;
				    swt-header-background-color: %s;
				    swt-header-color: %s;
				}
				Text, StyledText {
				    selection-background-color: %s;
				    selection-foreground-color: %s;
				}
				ToolBar, CoolBar, CBanner { background-color: %s; color: %s; }
				.MPartStack { swt-selected-tab-fill: %s; }
				"""
				.formatted(background, foreground, selectionBackground, selectionBackground, selectionForeground,
						background, currentLine, foreground, background, foreground, background, foreground,
						selectionBackground, selectionForeground, currentLine, foreground, selectionBackground,
						selectionForeground, background, foreground, selectionBackground);
	}
}
